#!/usr/bin/env node
'use strict';
// The trial notes as the commits carry them: every fix since note 3 ends its
// message with "Trial notes: N", and docs/trial-notes.md holds the long form
// only to note 943. This lists each note with its date, commit and the
// message's first sentence, newest first.
//   node scripts/notes-index.js > docs/notes-index.md
const { execSync } = require('child_process');
const log = execSync("git log --format='%H%x09%cs%x09%B%x1e' main", { encoding: 'utf8', maxBuffer: 1 << 28 });
const notes = new Map();
for (const rec of log.split('\x1e')) {
  const [hash, date, ...rest] = rec.trim().split('\t');
  if (!hash || !rest.length) continue;
  const body = rest.join('\t').trim();
  const m = body.match(/Trial notes?: ([\d, a-z]+)/);
  if (!m) continue;
  const text = body.replace(/\s*Trial notes?: [\d, a-z]+\s*$/, '').replace(/\s+/g, ' ');
  const first = (text.match(/^.{40,}?\.(?=\s+[A-Z(]|$)/) || [text])[0];
  const said = first.length > 300 ? `${first.slice(0, 297).replace(/\s+\S*$/, '')}...` : first;
  for (const n of m[1].match(/\d+/g) || []) if (!notes.has(+n)) notes.set(+n, { date, hash: hash.slice(0, 8), said });
}
const rows = [...notes.entries()].sort((a, b) => b[0] - a[0]);
console.log('# Trial notes index\n');
console.log(`Every fix ends its commit message with "Trial notes: N". This lists the ${rows.length} notes the commits carry, newest first, with the first sentence of each message; \`git show <commit>\` has the whole note. Notes up to 943 also have a long form in [trial-notes.md](trial-notes.md). Generated by \`node scripts/notes-index.js\`.\n`);
console.log('| Note | Date | Commit | What changed |\n| --- | --- | --- | --- |');
for (const [n, r] of rows) console.log(`| ${n} | ${r.date} | \`${r.hash}\` | ${r.said.replace(/\|/g, '\\|')} |`);
